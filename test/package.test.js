const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'HTML IDs are unique');
const game=html.match(/<script type="module" id="gameModule">([\s\S]*?)<\/script>/)[1];
for(const match of game.matchAll(/\$\('([^']+)'\)/g))assert(ids.includes(match[1]),match[1]);
assert(html.includes('"three":"./vendor/three.module.min.js"'));
assert(!html.includes('https://cdn.jsdelivr.net'),'No CDN requests at runtime');
const offline=html.match(/<script type="module" id="offlineThree">([\s\S]*?)<\/script>/)[1];
const direct={location:{protocol:'file:'},window:{},console};
vm.createContext(direct);vm.runInContext(offline,direct);
assert.equal(direct.__LOCAL_THREE__.REVISION,'170');
assert.equal(new direct.__LOCAL_THREE__.Vector3(3,4,0).length(),5);
const hosted={location:{protocol:'http:'}};
vm.createContext(hosted);vm.runInContext(offline,hosted);
assert.equal(hosted.__LOCAL_THREE__,undefined,'Hosted page imports the vendor file instead');
assert(fs.statSync(path.join(__dirname,'..','vendor/three.module.min.js')).size>600000);
assert(fs.readFileSync(path.join(__dirname,'..','vendor/THREE-LICENSE.txt'),'utf8').includes('MIT License'));
new Function(game.replace("const THREE=globalThis.__LOCAL_THREE__ || await import('three');",''));
console.log('PASS: script syntax, control IDs, offline file-open fallback, local vendor importmap, preserved MIT license, no CDN dependency.');
